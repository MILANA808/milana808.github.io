const assert = require("node:assert/strict");
const { createEvidenceKernel } = require("../aksi-evidence-kernel.js");
const kernel = createEvidenceKernel();
const animal = kernel.addClaim({ subject: "dog", predicate: "is_a", object: "mammal", source: "curated test fixture", confidence: 0.98, kind: "source" });
const mammal = kernel.addClaim({ subject: "mammal", predicate: "is_a", object: "animal", source: "curated test fixture", confidence: 0.93, kind: "source" });
assert.equal(kernel.size, 2);
assert.equal(kernel.query({ subject: "dog", predicate: "is_a", object: "mammal" }).status, "supported");
const inferred = kernel.query({ subject: "dog", predicate: "is_a", object: "animal" });
assert.equal(inferred.status, "supported");
assert.equal(inferred.inferences.length, 1);
assert.deepEqual(inferred.inferences[0].premises, [animal.id, mammal.id]);
assert.equal(inferred.inferences[0].confidence, 0.93);
assert.equal(kernel.query({ subject: "dog", predicate: "is_a", object: "plant" }).status, "unknown");
const explanation = kernel.explain({ subject: "dog", predicate: "is_a", object: "animal" });
assert.equal(explanation.derivations[0].rule, "is_a_transitivity");
assert.match(explanation.limitations[0], /does not mean false/);
kernel.addClaim({ subject: "dog", predicate: "is_a", object: "mammal", truth: false, source: "contrary test record", confidence: 0.4, kind: "hypothesis" });
assert.equal(kernel.query({ subject: "dog", predicate: "is_a", object: "mammal" }).status, "conflicted");
assert.throws(() => kernel.addClaim({ subject: "x", predicate: "is_a", object: "y" }), /source/);
assert.throws(() => kernel.addClaim({ subject: "x", predicate: "is_a", object: "y", source: "fixture", confidence: 1.5 }), /confidence/);
assert.throws(() => kernel.addClaim({ subject: "x", predicate: "is_a", object: "y", source: "fixture", kind: "magic" }), /unsupported claim kind/);
assert.throws(() => createEvidenceKernel({ maxClaims: 0 }), /maxClaims/);
const bounded = createEvidenceKernel({ maxClaims: 1 });
bounded.addClaim({ subject: "a", predicate: "related_to", object: "b", source: "fixture" });
assert.throws(() => bounded.addClaim({ subject: "b", predicate: "related_to", object: "c", source: "fixture" }), /capacity/);
const exported = kernel.snapshot();
assert.equal(exported.schema, "AKSI-EVIDENCE-GRAPH/1");
assert.ok(Object.isFrozen(exported));
console.log("AKSI Evidence Kernel tests: OK");
