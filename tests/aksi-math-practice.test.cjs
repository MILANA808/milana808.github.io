"use strict";
const assert = require("node:assert/strict");
const math = require("../aksi-math-practice.js");
global.AKSIMathPractice = math;
global.AKSISemanticReasoning = require("../aksi-semantic-reasoning.js");
const dialogue = require("../aksi-dialogue-intelligence.js");
assert.equal(math.version, "1.0.0");
assert.equal(math.list().length, 4);
const theorem = dialogue.answer("Объясни теорему Пифагора");
assert.equal(theorem.status, "grounded_math_reference");
assert.match(theorem.text, /c² = a² \+ b²/);
assert.match(theorem.text, /Идея доказательства/);
assert.equal(theorem.theorem, "pythagoras");
const practice = dialogue.answer("Дай практику по формуле Байеса");
assert.equal(practice.intent, "math_practice");
assert.match(practice.text, /Задача для тебя/);
assert.match(practice.text, /30,8%/);
const example = dialogue.answer("Приведи пример применения энтропии Шеннона");
assert.equal(example.intent, "math_example");
assert.match(example.text, /1 бит/);
const logic = dialogue.answer("Объясни правило modus ponens");
assert.match(logic.text, /P → Q/);
const catalog = dialogue.answer("Покажи теоремы");
assert.equal(catalog.status, "catalog");
assert.equal(math.find("пифагора").id, "pythagoras");
assert.equal(math.answer("Что такое флуксометр?"), null);
console.log("AKSI mathematical practice tests: all passed");
