const assert = require("node:assert/strict");
const vm = require("node:vm");
const fs = require("node:fs");
const path = require("node:path");
const root = path.join(__dirname, "..");
const html = fs.readFileSync(path.join(root, "index.html"), "utf8");
const sw = fs.readFileSync(path.join(root, "sw.js"), "utf8");
const inlineScript = html.match(/<script>\s*([\s\S]*?async function ask\(q\)[\s\S]*?)<\/script>/);

const weatherTag = '<script src="/aksi-weather.js?v=2"></script>';
const evidenceTag = '<script src="/modules/claim-evidence.js?v=2"></script>';
const routerTag = '<script src="/aksi-answer-router.js?v=5"></script>';
const semanticTag = '<script src="/aksi-semantic-reasoning.js?v=3"></script>';
const knowledgeTag = '<script src="/aksi-knowledge-base.js?v=2"></script>';
assert.ok(html.includes(weatherTag), "weather adapter cache version must be refreshed");
assert.ok(html.includes(routerTag), "answer router cache version must be refreshed");
assert.ok(html.includes(evidenceTag), "claim evidence module must be loaded");
assert.ok(html.includes(semanticTag), "semantic engine cache version must be refreshed");
assert.ok(html.includes(knowledgeTag), "knowledge base cache version must be refreshed");
assert.ok(html.indexOf(weatherTag) < html.indexOf(routerTag), "weather adapter must load before router");
assert.ok(html.indexOf(knowledgeTag) < html.indexOf(evidenceTag), "knowledge base must load before evidence module");
assert.ok(html.indexOf(evidenceTag) < html.indexOf(routerTag), "claim evidence module must load before router");
assert.ok(html.indexOf(routerTag) < html.indexOf("async function ask(q)"), "router must load before chat handler");
assert.ok(html.indexOf(semanticTag) < html.indexOf("async function ask(q)"), "semantic engine must load before chat handler");
const cacheVersion = sw.match(/var CACHE = "aksi-shell-v(\d+)"/);
assert.ok(cacheVersion, "service worker cache must declare a version");
assert.match(sw, new RegExp("AKSI SW v" + cacheVersion[1]), "service worker header and cache version must agree");
assert.ok(Number(cacheVersion[1]) > 311, "service worker cache must invalidate the v311 shell");
assert.ok(sw.includes("/aksi-.*\\.js$/"), "JavaScript assets must use network-first strategy");

const askStart = html.indexOf("async function ask(q)");
const askEnd = html.indexOf("async function diagnostics()", askStart);
assert.ok(askStart >= 0 && askEnd > askStart, "chat and diagnostics functions must be present");
assert.ok(inlineScript, "main inline application script must be present");
assert.doesNotThrow(() => new vm.Script(inlineScript[1], { filename: "index-inline.js" }), "inline application script must parse without syntax errors");
const ask = html.slice(askStart, askEnd);
assert.ok(ask.includes('kernel.runTask("answer.route"'), "answer routing must execute as a bounded kernel task");
assert.ok(ask.includes('kernel.getModule("answer.router")'), "answer routing must require an initialized kernel module");
assert.ok(ask.includes('await kernel.boot()'), "chat must await kernel initialization before routing");
assert.ok(ask.indexOf("answerRouter.answer(q") < ask.indexOf("AKSI_DNA_TOPOLOGY.generate"), "explicit answer router must run before fallback generator");
assert.match(ask, /if\(routed&&routed\.handled\)/, "handled answers must return early without diagnostic fallback");
assert.match(html, /check\('Answer router'/, "diagnostics must expose answer router availability");
assert.match(html, /check\('Semantic reasoning'/, "diagnostics must expose semantic engine availability");
assert.match(html, /check\('Weather command'/, "diagnostics must verify weather command parsing");
assert.match(html, /серверный backend намеренно отключён/, "diagnostics must not report disabled backend as healthy");
assert.ok(html.includes('id="runAnswerSelfTest"'), "UI must expose the local answer self-test");
assert.match(html, /ОЦЕНКА ДОКАЗАТЕЛЬСТВ/, "web evidence panel must show explicit review state");
assert.match(html, /НЕДОСТАТОЧНО ДАННЫХ/, "unreviewed web evidence must not be presented as verified");
assert.match(html, /лексический фильтр:/, "evidence panel must expose the screening method");
assert.match(html, /покрытие терминов:/, "evidence panel must expose lexical coverage");
assert.ok(html.includes("/docs/AKSI-OS-ARCHITECTURE.md"), "homepage must expose the open OS architecture");
assert.ok(html.includes("/system/aksi-os-status.json"), "homepage must expose machine-readable system status");
assert.ok(html.includes('id="aksiKernelStatus"'), "homepage must expose kernel runtime diagnostics");
assert.ok(html.includes('/modules/aksi-system-kernel.js?v=1'), "homepage must load the kernel API");
assert.ok(html.includes('/system/aksi-boot.js?v=1'), "homepage must load the kernel bootstrap");
assert.match(sw, /var CACHE = "aksi-shell-v\\d+"/);
assert.ok(html.indexOf('src="/aksi-answer-router.js?v=5"') < html.indexOf('src="/system/aksi-boot.js?v=1"'), "kernel boot must run after answer router loads");
assert.match(html, /async function runAnswerSelfTest\(\)/, "local answer self-test must be implemented");
const selfTestStart = html.indexOf("async function runAnswerSelfTest()");
const selfTestEnd = html.indexOf("$('runAnswerSelfTest').addEventListener", selfTestStart);
const selfTest = html.slice(selfTestStart, selfTestEnd);
assert.ok(selfTestEnd > selfTestStart, "self-test function must have a clear boundary");
assert.ok(!selfTest.includes("fetch(") && !selfTest.includes("weather.answer("), "self-test must not make network calls");
console.log("AKSI browser release contract: OK");
