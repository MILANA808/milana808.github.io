"use strict";
const assert = require("node:assert/strict");
global.AKSISemanticReasoning = require("../aksi-semantic-reasoning.js");
const engine = require("../aksi-dialogue-intelligence.js");
assert.equal(engine.version, "1.0.0");
assert.equal(engine.bayesUpdate(0.1, 0.9, 0.2), 0.3333333333333333);
assert.equal(engine.entropy([0.5, 0.5]), 1);
assert.equal(engine.modusPonens({if:"дождь",then:"мокро"}, {subject:"улица",predicate:"дождь"}).conclusion.predicate, "мокро");
assert.deepEqual(engine.relationClosure([{from:"a",to:"b"},{from:"b",to:"c"}],"a","c"), ["a","b","c"]);
assert.equal(engine.relationClosure([{from:"a",to:"b"}],"a","z"), null);
const simple = engine.answer("Объясни проще математику");
assert.equal(simple.status, "explained");
assert.match(simple.text, /Математика/);
const why = engine.answer("Почему искусственный интеллект всегда прав?");
assert.equal(why.status, "causal_evidence_missing");
const compare = engine.answer("Сопоставь математику и геометрию");
assert.equal(compare.status, "compared");
const unknown = engine.answer("Почему флуксометр летает?");
assert.equal(unknown.status, "insufficient_grounding");
assert.match(unknown.text, /нужны дополнительные факты или уточнение/i);
assert.throws(() => engine.entropy([0.2, 0.2]), /sum/);
console.log("AKSI dialogue intelligence: all tests passed");
