const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const inference = require('../aksi-symbolic-inference.js');

test('derives a conclusion through a chain of explicit rules', () => {
  const result = inference.infer('логика: если идет дождь, то земля мокрая; если земля мокрая, то скользко; идет дождь; следует ли скользко?');
  assert.equal(result.ok, true);
  assert.equal(result.status, 'proven');
  assert.equal(result.query, 'скользко');
  assert.equal(result.proof.at(-1).to, 'скользко');
  assert.ok(result.proof.some(step => step.type === 'rule'));
});

test('does not claim an unproven conclusion is false', () => {
  const result = inference.infer('логика: идет дождь; следует ли земля мокрая?');
  assert.equal(result.status, 'not_derived');
  assert.match(result.text, /не доказывает, что утверждение ложно/);
});

test('accepts explicit facts and simple implication rules', () => {
  const result = inference.infer('выведи: факт: сервер доступен; если сервер доступен, то можно проверить API; следует ли можно проверить API?');
  assert.equal(result.status, 'proven');
});

test('rejects requests without a query', () => {
  const result = inference.infer('логика: если a, то b; a');
  assert.equal(result.ok, false);
  assert.equal(result.status, 'invalid_input');
});

test('keeps propositions exact rather than guessing semantic equivalence', () => {
  const result = inference.infer('логика: идет дождь; следует ли улица мокрая?');
  assert.equal(result.status, 'not_derived');
});

test('main adaptive core routes explicit logic prompts into the reasoner', async () => {
  const storage = new Map();
  const sandbox = {
    AKSISymbolicInference: inference,
    localStorage: {
      getItem: key => storage.has(key) ? storage.get(key) : null,
      setItem: (key, value) => storage.set(key, String(value))
    },
    console
  };
  sandbox.window = sandbox;
  vm.runInNewContext(fs.readFileSync('aksi-unified-adaptive-core.js', 'utf8'), sandbox, { filename: 'aksi-unified-adaptive-core.js' });
  const result = await sandbox.AKSI_UNIFIED_CORE.answer(
    'логика: если идет дождь, то земля мокрая; идет дождь; следует ли земля мокрая?'
  );
  assert.equal(result.source, 'aksi-symbolic-inference');
  assert.equal(result.inference.status, 'proven');
  assert.equal(sandbox.AKSI_UNIFIED_CORE.inspect().modules.symbolicInference, true);
});

test('uses only explicitly declared concept aliases across facts, rules, and query', () => {
  const result = inference.infer('логика: синоним: авто = автомобиль; факт: авто движется; если автомобиль движется, то есть движение; следует ли есть движение?');
  assert.equal(result.status, 'proven');
  assert.equal(result.query, 'есть движение');
  assert.equal(result.facts[0], 'автомобиль движется');
  assert.equal(result.aliases.length, 1);
});

test('does not guess undeclared semantic equivalence', () => {
  const result = inference.infer('логика: автомобиль движется; следует ли авто движется?');
  assert.equal(result.status, 'not_derived');
});

test('parses typed relations into explicit propositions usable by inference', () => {
  const result = inference.infer('логика: отношение: кот --является--> животное; если кот является животное, то кот живое существо; следует ли кот живое существо?');
  assert.equal(result.status, 'proven');
  assert.deepEqual(result.relations[0], {
    subject: 'кот', predicate: 'является', object: 'животное',
    statement: 'кот является животное'
  });
  assert.ok(result.proof.some(step => step.type === 'rule'));
});

test('detects explicit contradictions and preserves both proof traces', () => {
  const result = inference.infer('логика: факт: дверь открыта; факт: не дверь открыта; следует ли дверь открыта?');
  assert.equal(result.status, 'proven_with_contradictions');
  assert.equal(result.contradictions.length, 1);
  assert.equal(result.contradictions[0].positive, 'дверь открыта');
  assert.equal(result.contradictions[0].negative, 'не дверь открыта');
  assert.ok(Array.isArray(result.contradictions[0].positiveProof));
  assert.ok(Array.isArray(result.contradictions[0].negativeProof));
});

test('detects contradictions generated by explicit rules even if the query is not derived', () => {
  const result = inference.infer('логика: факт: сервер доступен; если сервер доступен, то не сервер доступен; следует ли сервер перезагружен?');
  assert.equal(result.status, 'contradiction_detected');
  assert.equal(result.contradictions.length, 1);
});

test('applies an explicit variable rule to different named entities', () => {
  const input = 'логика: отношение: Сократ --является--> человек; отношение: Платон --является--> человек; если {x} является человек, то {x} смертен; следует ли сократ смертен?';
  const result = inference.infer(input);
  assert.equal(result.status, 'proven');
  assert.equal(result.query, 'сократ смертен');
  const applied = result.proof.find(step => step.type === 'rule');
  assert.equal(applied.from, 'сократ является человек');
  assert.equal(applied.to, 'сократ смертен');
  assert.equal(applied.bindings.x, 'сократ');
});

test('requires repeated variables to match the same entity', () => {
  const result = inference.infer('логика: факт: сократ является человек; факт: платон смертен; если {x} является человек, то {x} смертен; следует ли сократ смертен?');
  assert.equal(result.status, 'not_derived');
});

test('variable rules can derive a contradiction and retain its origin', () => {
  const result = inference.infer('логика: факт: сократ является человек; если {x} является человек, то {x} смертен; если {x} является человек, то не {x} смертен; следует ли сократ смертен?');
  assert.equal(result.status, 'proven_with_contradictions');
  assert.equal(result.contradictions[0].positive, 'сократ смертен');
  assert.equal(result.contradictions[0].negative, 'не сократ смертен');
  assert.ok(result.contradictions[0].negativeProof.some(step => step.type === 'rule'));
});

