import fs from "node:fs";
import vm from "node:vm";
import assert from "node:assert/strict";
const html = fs.readFileSync("quantum-mind/index.html", "utf8");
const start = html.indexOf('<script type="module">');
assert.notEqual(start, -1, "module script is required");
const bodyStart = start + '<script type="module">'.length;
const end = html.indexOf('</script>', bodyStart);
assert.ok(end > bodyStart, "module script must close");
new Function(html.slice(bodyStart, end));
for (const marker of ["useWebEvidence", "useLocalMemory", "AKSI_INTERNET.gather", "AKSICalculator.evaluate", "AksiMemory.history", "Выбрать этот ответ", "Повторить измерение", "receipt", "safeScore", "sourceFootnote", "verifyReceipt", "receiptCheck", "ЦЕЛОСТНОСТЬ ПОДТВЕРЖДЕНА"]) assert.ok(html.includes(marker), "missing integration: " + marker);
const mathContext = {};
vm.runInNewContext(fs.readFileSync("aksi-calculator.js", "utf8"), mathContext);
const calc = mathContext.AKSICalculator;
assert.equal(calc.evaluate("2+2*3").value, 8);
assert.equal(calc.evaluate("(2+3)^2").value, 25);
assert.equal(calc.evaluate("-3^2").value, -9);
assert.equal(calc.evaluate("2^-2").value, 0.25);
assert.equal(calc.evaluate("sqrt(81)").value, 9);
assert.equal(calc.evaluate("1/0").ok, false);
assert.equal(calc.evaluate("alert(1)").ok, false);
assert.ok(html.includes('if($("useLocalMemory").checked&&window.AksiMemory)'), "memory writes must require explicit opt-in");
assert.ok(html.includes("delete payload.integrity"), "receipt verifier must exclude integrity metadata before recomputing the digest");
assert.ok(html.includes("actual===expected"), "receipt verifier must compare recomputed and stored hashes");
console.log("AKSI Answer Engine integrity checks: OK");
